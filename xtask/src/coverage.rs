//! `cargo xtask coverage [--check]`: coverage badges in README.md, between
//! the coverage markers. Unlike `progress`, this needs the x86_64 cross
//! toolchain (objdump, kernel headers, a built guest program).
//!
//! - x86 decoder: instructions of the statically linked glibc program
//!   `c/hello` that armor decodes with objdump's length.
//! - syscalls: x86_64 syscall numbers armor handles (`is_implemented`) out
//!   of those defined in the kernel's unistd_64.h.
//!
//! See docs/conventions.md.

use std::fs;
use std::path::Path;

use crate::decoder_check::decoded_fraction;
use crate::progress::{badge_color, percent, replace_between, shields_escape};
use crate::{Paths, build_one};

const START_MARKER: &str = "<!-- coverage:start -->";
const END_MARKER: &str = "<!-- coverage:end -->";
const UNISTD_64: &str = "/usr/x86_64-linux-gnu/include/asm/unistd_64.h";
/// The guest program whose code (mostly static glibc) the decoder badge
/// measures.
const REFERENCE_PROGRAM: &str = "c/hello";

pub fn run(check: bool) -> Result<(), String> {
    let paths = Paths::new();
    let program = build_one(&paths, REFERENCE_PROGRAM)?;
    let (decoded, total) = decoded_fraction(&program.to_string_lossy())?;
    let numbers = syscall_numbers(Path::new(UNISTD_64))?;
    let implemented = numbers
        .iter()
        .filter(|&&n| armor_linux::syscall::is_implemented(n))
        .count();

    let block = render(decoded, total, implemented, numbers.len());
    let readme_path = paths.root.join("README.md");
    let readme = fs::read_to_string(&readme_path)
        .map_err(|e| format!("cannot read {}: {e}", readme_path.display()))?;
    let updated = replace_between(&readme, &block, START_MARKER, END_MARKER)?;
    if updated == readme {
        println!("README.md coverage is up to date");
    } else if check {
        return Err("README.md coverage is stale: run `cargo xtask coverage`".to_string());
    } else {
        fs::write(&readme_path, updated)
            .map_err(|e| format!("cannot write {}: {e}", readme_path.display()))?;
        println!("README.md coverage updated");
    }
    Ok(())
}

/// Syscall numbers from `#define __NR_<name> <number>` lines.
fn syscall_numbers(header: &Path) -> Result<Vec<u64>, String> {
    let text = fs::read_to_string(header).map_err(|e| {
        format!(
            "cannot read {}: {e} (install libc6-dev-amd64-cross, docs/environment.md)",
            header.display()
        )
    })?;
    Ok(parse_syscall_numbers(&text))
}

fn parse_syscall_numbers(text: &str) -> Vec<u64> {
    let mut numbers: Vec<u64> = text
        .lines()
        .filter_map(|line| {
            let mut words = line.split_whitespace();
            (words.next()? == "#define" && words.next()?.starts_with("__NR_")).then_some(())?;
            words.next()?.parse().ok()
        })
        .collect();
    numbers.sort_unstable();
    numbers.dedup();
    numbers
}

fn render(decoded: usize, total: usize, implemented: usize, syscalls: usize) -> String {
    // One decimal for the decoder: it moves in small steps.
    let tenths = (decoded * 1000).checked_div(total).unwrap_or(0);
    let decoder_text = format!("{}.{}%", tenths / 10, tenths % 10);
    let syscall_text = format!("{implemented}/{syscalls}");
    let decoder = badge(
        "x86 decoder",
        &decoder_text,
        badge_color(percent(decoded, total)),
    );
    let syscall = badge(
        "syscalls",
        &syscall_text,
        badge_color(percent(implemented, syscalls)),
    );
    format!(
        "{START_MARKER}\n<!-- Generated by `cargo xtask coverage`. Do not edit. -->\n\
         ![x86 decoder {decoder_text}]({decoder}) ![syscalls {syscall_text}]({syscall})\n\
         {END_MARKER}"
    )
}

fn badge(label: &str, message: &str, color: &str) -> String {
    let escape = |text: &str| shields_escape(text).replace('/', "%2F");
    format!(
        "https://img.shields.io/badge/{}-{}-{color}",
        escape(label),
        escape(message)
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn syscall_numbers_are_parsed_from_the_header() {
        let header = "#ifndef _ASM_UNISTD_64_H\n#define __NR_read 0\n#define __NR_write 1\n\
                      #define __NR_x32_alias 1\n#define _ASM_UNISTD_64_H 1\n";
        assert_eq!(parse_syscall_numbers(header), [0, 1]);
    }

    #[test]
    fn badges_show_one_decimal_and_a_fraction() {
        let block = render(954, 1000, 17, 375);
        assert!(block.contains("x86_decoder-95.4%25-green"), "{block}");
        assert!(block.contains("syscalls-17%2F375-orange"), "{block}");
        assert!(block.starts_with(START_MARKER) && block.ends_with(END_MARKER));
    }
}
