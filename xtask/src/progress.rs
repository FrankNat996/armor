//! `cargo xtask progress`: completion percentages shown in README.md.
//!
//! Counts the ticked checklist items of each milestone in docs/roadmap.md and
//! rewrites the README block between the progress markers. With `--check` it
//! only verifies that the README is up to date. See docs/conventions.md.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

const START_MARKER: &str = "<!-- progress:start -->";
const END_MARKER: &str = "<!-- progress:end -->";

/// Short English names for the README's progress table.
/// A milestone missing here is an error, so new milestones cannot slip into
/// the README untranslated.
const MILESTONE_NAMES: &[(&str, &str)] = &[
    ("M0", "Infrastructure"),
    ("M1", "Static hello world"),
    ("M2", "Full decoder, static glibc programs"),
    ("M3", "Threads, signals, guest memory"),
    ("M4", "Floating point and SIMD"),
    ("M5", "Dynamic linking and runtime"),
    ("M6", "AArch64 JIT and performance"),
    ("M7", "The installer for everyone: any x86 program"),
    ("M8", "Games and Steam"),
    ("M9", "Any ARM64"),
    ("M10", "The reference"),
    ("M11", "The best engine"),
];

#[derive(Debug, PartialEq)]
struct Milestone {
    id: String,
    done: usize,
    total: usize,
}

pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let roadmap_path = root.join("docs/roadmap.md");
    let readme_path = root.join("README.md");
    let roadmap = read(&roadmap_path)?;
    let readme = read(&readme_path)?;

    let milestones = parse_roadmap(&roadmap);
    if milestones.is_empty() {
        return Err(format!("no milestones found in {}", roadmap_path.display()));
    }
    let updated = replace_block(&readme, &render(&milestones)?)?;

    if updated == readme {
        println!("README.md progress is up to date");
    } else if check {
        return Err("README.md progress is stale: run `cargo xtask progress`".to_string());
    } else {
        fs::write(&readme_path, updated)
            .map_err(|e| format!("cannot write {}: {e}", readme_path.display()))?;
        println!("README.md progress updated");
    }
    Ok(())
}

fn read(path: &Path) -> Result<String, String> {
    fs::read_to_string(path).map_err(|e| format!("cannot read {}: {e}", path.display()))
}

/// A milestone section starts at a `## M<digits> ...` heading and ends at the
/// next `## ` heading. Only top-level `- [ ]` / `- [x]` lines are items;
/// indented sub-bullets are details of their parent item.
fn parse_roadmap(text: &str) -> Vec<Milestone> {
    let mut milestones = Vec::new();
    let mut current: Option<Milestone> = None;
    for line in text.lines() {
        if let Some(heading) = line.strip_prefix("## ") {
            milestones.extend(current.take());
            current = milestone_id(heading).map(|id| Milestone {
                id,
                done: 0,
                total: 0,
            });
        } else if let Some(milestone) = current.as_mut() {
            if line.starts_with("- [x]") || line.starts_with("- [X]") {
                milestone.done += 1;
                milestone.total += 1;
            } else if line.starts_with("- [ ]") {
                milestone.total += 1;
            }
        }
    }
    milestones.extend(current);
    milestones
}

/// `M1 — Hello world statico (giorni)` -> `M1`.
fn milestone_id(heading: &str) -> Option<String> {
    let id = heading.split_whitespace().next()?;
    let digits = id.strip_prefix('M')?;
    let is_id = !digits.is_empty() && digits.chars().all(|c| c.is_ascii_digit());
    is_id.then(|| id.to_string())
}

fn english_name(id: &str) -> Result<&'static str, String> {
    MILESTONE_NAMES
        .iter()
        .find(|(known, _)| *known == id)
        .map(|(_, name)| *name)
        .ok_or_else(|| format!("milestone {id} has no English name: add it to MILESTONE_NAMES"))
}

fn render(milestones: &[Milestone]) -> Result<String, String> {
    let done: usize = milestones.iter().map(|m| m.done).sum();
    let total: usize = milestones.iter().map(|m| m.total).sum();
    let overall = percent(done, total);

    let mut out = String::new();
    out.push_str(START_MARKER);
    out.push('\n');
    out.push_str(
        "<!-- Generated by `cargo xtask progress` from docs/roadmap.md. Do not edit. -->\n",
    );
    let _ = writeln!(
        out,
        "![Roadmap {overall}%]({})\n",
        badge_url("roadmap", overall)
    );
    out.push_str("| Milestone | Progress | Items done |\n|---|---|---|\n");
    for m in milestones {
        let pct = percent(m.done, m.total);
        let _ = writeln!(
            out,
            "| {} | ![{} {pct}%]({}) | {}/{} |",
            english_name(&m.id)?,
            m.id,
            badge_url(&m.id, pct),
            m.done,
            m.total
        );
    }
    out.push_str(END_MARKER);
    Ok(out)
}

/// Rounded down, so 100% means every item is done.
pub(crate) fn percent(done: usize, total: usize) -> usize {
    (done * 100).checked_div(total).unwrap_or(0)
}

/// Static shields.io badge, e.g. `[M0 | 100%]`.
fn badge_url(label: &str, pct: usize) -> String {
    format!(
        "https://img.shields.io/badge/{}-{}-{}",
        shields_escape(label),
        shields_escape(&format!("{pct}%")),
        badge_color(pct)
    )
}

/// Escaping rules of shields.io static badge paths.
pub(crate) fn shields_escape(text: &str) -> String {
    text.replace('-', "--")
        .replace('_', "__")
        .replace(' ', "_")
        .replace('%', "%25")
}

pub(crate) fn badge_color(pct: usize) -> &'static str {
    match pct {
        100.. => "brightgreen",
        67.. => "green",
        34.. => "yellow",
        1.. => "orange",
        0 => "lightgrey",
    }
}

fn replace_block(readme: &str, block: &str) -> Result<String, String> {
    replace_between(readme, block, START_MARKER, END_MARKER)
}

/// Replaces everything from `start_marker` to `end_marker`, inclusive.
pub(crate) fn replace_between(
    readme: &str,
    block: &str,
    start_marker: &str,
    end_marker: &str,
) -> Result<String, String> {
    let missing = || format!("README.md needs the markers {start_marker} and {end_marker}");
    let start = readme.find(start_marker).ok_or_else(missing)?;
    let end = readme[start..].find(end_marker).ok_or_else(missing)? + start + end_marker.len();
    Ok(format!("{}{block}{}", &readme[..start], &readme[end..]))
}

#[cfg(test)]
mod tests {
    use super::*;

    const ROADMAP: &str = "\
# Roadmap
- [x] not inside a milestone

## M0 — Infrastruttura
- [x] one
- [X] two

## M1 — Hello world statico (giorni)
- [x] three
- [ ] four
  - [ ] nested detail, not an item
  - plain sub-bullet

## Oltre
- [ ] not a milestone
";

    fn milestone(id: &str, done: usize, total: usize) -> Milestone {
        Milestone {
            id: id.to_string(),
            done,
            total,
        }
    }

    #[test]
    fn roadmap_counts_top_level_items_per_milestone() {
        assert_eq!(
            parse_roadmap(ROADMAP),
            vec![milestone("M0", 2, 2), milestone("M1", 1, 2)]
        );
    }

    #[test]
    fn milestone_id_needs_m_and_digits() {
        assert_eq!(milestone_id("M12 — Title").as_deref(), Some("M12"));
        assert_eq!(milestone_id("Oltre"), None);
        assert_eq!(milestone_id("M — Title"), None);
        assert_eq!(milestone_id("Mx — Title"), None);
    }

    #[test]
    fn percent_rounds_down_and_handles_empty_milestones() {
        assert_eq!(percent(4, 31), 12);
        assert_eq!(percent(30, 31), 96);
        assert_eq!(percent(2, 2), 100);
        assert_eq!(percent(0, 0), 0);
    }

    #[test]
    fn badges_escape_shields_syntax() {
        assert_eq!(
            badge_url("M0", 100),
            "https://img.shields.io/badge/M0-100%25-brightgreen"
        );
        assert_eq!(shields_escape("a-b_c d"), "a--b__c_d");
    }

    #[test]
    fn badge_color_follows_thresholds() {
        let colors: Vec<_> = [0, 1, 34, 67, 99, 100].map(badge_color).into();
        assert_eq!(
            colors,
            [
                "lightgrey",
                "orange",
                "yellow",
                "green",
                "green",
                "brightgreen"
            ]
        );
    }

    #[test]
    fn unknown_milestone_is_an_error() {
        assert!(render(&[milestone("M99", 0, 1)]).is_err());
    }

    #[test]
    fn block_between_markers_is_replaced() {
        let readme = format!("intro\n{START_MARKER}\nold\n{END_MARKER}\noutro\n");
        let block = format!("{START_MARKER}\nnew\n{END_MARKER}");
        assert_eq!(
            replace_block(&readme, &block).unwrap(),
            format!("intro\n{START_MARKER}\nnew\n{END_MARKER}\noutro\n")
        );
    }

    #[test]
    fn missing_markers_are_an_error() {
        assert!(replace_block("no markers here", "block").is_err());
    }
}
